"""
Own 16x16 icons for the Churn's items that used to borrow a look-alike's
sprite (ITEM_DB[..].look). Writes src/09_art_icons.lua (adds to CHURN.art,
after 09_art_churn) and, with --sheet, a contact sheet PNG to look at.

    python3 tools/paint_icons.py [--sheet previews/icons_sheet.png]

Families are drawn from a base and a mark (books: the topic's symbol on the
cover; tapes: a label pattern each). The rest are drawn by hand below:
'#' = ink, anything else = paper; each is centered in 16x16.
"""
import argparse
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "09_art_icons.lua"
N = 16


def grid(rows):
    """Rows of any size up to 16x16, centered, as 16 strings of '#' and '.'."""
    rows = [r.rstrip() for r in rows]
    while rows and not rows[-1].strip():
        rows.pop()
    while rows and not rows[0].strip():
        rows.pop(0)
    w = max(len(r) for r in rows)
    assert w <= N and len(rows) <= N, (w, len(rows))
    left, top = (N - w) // 2, (N - len(rows)) // 2
    out = ["." * N for _ in range(N)]
    for y, r in enumerate(rows):
        line = list(out[top + y])
        for x, c in enumerate(r):
            if c == "#":
                line[left + x] = "#"
        out[top + y] = "".join(line)
    return out


def art(text):
    return grid([line for line in text.strip("\n").split("\n")])


