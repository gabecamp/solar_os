def all_icons():
    icons = {}
    for item, mark in BOOK_MARKS.items():
        icons[item] = book(mark)
    for item, label in TAPE_LABELS.items():
        icons[item] = tape(label)
    for item, text in HAND.items():
        icons[item] = art(text)
    for item, rows in icons.items():
        assert len(rows) == N and all(len(r) == N for r in rows), item
        assert any("#" in r for r in rows), item
    return icons


def lua(icons):
    out = ["-- GENERATED by tools/paint_icons.py (do not edit by hand): own 16x16",
           "-- icons for the items that borrowed a look-alike's sprite ('#' = ink).",
           "for id, rows in pairs({"]
    for item in sorted(icons):
        out.append("    %s = {" % item)
        for r in icons[item]:
            out.append('        "%s",' % r)
        out.append("    },")
    out.append("}) do CHURN.art[id] = rows end")
    return "\n".join(out) + "\n"


def sheet(icons, path, extra=None):
    import pygame
    names = sorted(icons)
    if extra:
        names += sorted(extra)
        icons = dict(icons, **extra)
    cols, cell, pad = 10, 16 * 3, 22
    rows = (len(names) + cols - 1) // cols
    pygame.init()
    font = pygame.font.Font(None, 14)
    surf = pygame.Surface((cols * (cell + 12), rows * (cell + pad)))
    surf.fill((255, 255, 255))
    for i, n in enumerate(names):
        x, y = (i % cols) * (cell + 12) + 6, (i // cols) * (cell + pad) + 4
        for yy, r in enumerate(icons[n]):
            for xx, c in enumerate(r):
                if c == "#":
                    surf.fill((0, 0, 0), (x + xx * 3, y + yy * 3, 3, 3))
        pygame.draw.rect(surf, (200, 200, 200), (x - 1, y - 1, cell + 2, cell + 2), 1)
        surf.blit(font.render(n[:14], True, (0, 0, 0)), (x, y + cell + 3))
    pygame.image.save(surf, str(path))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sheet", help="also write a contact sheet PNG here")
    a = ap.parse_args()
    icons = all_icons()
    OUT.write_text(lua(icons))
    print("%d icons -> %s" % (len(icons), OUT.relative_to(ROOT)))
    if a.sheet:
        sheet(icons, a.sheet)
        print("sheet ->", a.sheet)


if __name__ == "__main__":
    main()
