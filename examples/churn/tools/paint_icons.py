def book(mark):
    g = [list("." * N) for _ in range(N)]
    for x in range(2, 14):
        g[1][x] = g[14][x] = "#"
    for y in range(1, 15):
        g[y][2] = g[y][13] = g[y][4] = "#"
    for x in range(4, 14):
        g[12][x] = "#"
    m = [r for r in mark.strip("\n").split("\n")]
    for y, r in enumerate(m):
        for x, c in enumerate(r):
            if c == "#":
                g[3 + y][6 + x] = "#"
    return ["".join(r) for r in g]


